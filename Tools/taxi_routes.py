"""Write Routes.lua: the flown length of every flight path, into lib.YARDS.

The client gives no flight duration, so LibTaxiTime works it out from
the length of the path the taxi flies and one speed, 30 yd/s: InFlight's
measured Classic times (References/Addons/MapMinimap/InFlightTaxiTimer, MIT)
against these lengths give 29.96 yd/s median over 266 direct routes, stdev
0.16 (multi-hop routes: the sum of their hops, within a second or two).
The lengths come from the client's own tables, exported from wago.tools
(product wow_classic_beta) into C:/Projects/WoW/References/Forever/db/:

    forever-taxipath-<build>.csv      ID, FromTaxiNode, ToTaxiNode, Cost
    forever-taxipathnode-<build>.csv  Loc_0..2, PathID, NodeIndex, ContinentID, Flags, Delay, ...
    forever-taxinodes-<build>.csv     Name_lang, ..., ID (names, for the comments only)

A path's length is the sum of the straight segments between its waypoints, in
NodeIndex order. Paths with a stop (Delay), a flag (teleports, stops) or a
change of continent are boats and zeppelins, never a flight master's, and are
left out. Standard library only.

    python Tools/taxi_routes.py               # newest build in the db folder
    python Tools/taxi_routes.py --check       # compare without writing (exit 1 if stale)
    python Tools/taxi_routes.py --db DIR --build 1.60.1.70532
"""
import argparse
import csv
import math
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_DB = ROOT.parent / "References" / "Forever" / "db"
OUT = ROOT / "Routes.lua"
LIB = ROOT / "LibTaxiTime.lua"


def lib_minor():
    m = re.search(r'local MAJOR, MINOR = "LibTaxiTime-1.0", (\d+)', LIB.read_text(encoding="utf-8"))
    if not m:
        raise SystemExit("no MINOR in LibTaxiTime.lua")
    return int(m.group(1))


def newest_build(db):
    builds = []
    for p in db.glob("forever-taxipath-*.csv"):
        m = re.fullmatch(r"forever-taxipath-(\d+\.\d+\.\d+\.\d+)\.csv", p.name)
        if m:
            builds.append(tuple(int(x) for x in m.group(1).split(".")))
    if not builds:
        raise SystemExit("no forever-taxipath-<build>.csv in " + str(db))
    return ".".join(str(x) for x in max(builds))


def read(db, table, build):
    path = db / ("forever-%s-%s.csv" % (table, build))
    with open(path, encoding="utf-8", newline="") as f:
        return list(csv.DictReader(f))


def lengths(db, build):
    paths = {int(r["ID"]): (int(r["FromTaxiNode"]), int(r["ToTaxiNode"])) for r in read(db, "taxipath", build)}
    names = {int(r["ID"]): r["Name_lang"] for r in read(db, "taxinodes", build)}
    points = defaultdict(list)
    for r in read(db, "taxipathnode", build):
        points[int(r["PathID"])].append(r)
    out = {}
    for pid, (src, dst) in sorted(paths.items()):
        pts = sorted(points.get(pid, []), key=lambda r: int(r["NodeIndex"]))
        if len(pts) < 2 or src not in names or dst not in names:
            continue
        if any(r["Delay"] != "0" or r["Flags"] != "0" for r in pts):
            continue
        if len({r["ContinentID"] for r in pts}) != 1:
            continue
        yards = 0.0
        for a, b in zip(pts, pts[1:]):
            yards += math.dist([float(a["Loc_%d" % i]) for i in range(3)],
                               [float(b["Loc_%d" % i]) for i in range(3)])
        key = "%d>%d" % (src, dst)
        if key in out and out[key][0] != round(yards):   # 84>85 is listed twice, the same path
            raise SystemExit("two paths of different lengths for " + key)
        out[key] = (round(yards), names[src], names[dst])
    return out


def render(build, routes, minor):
    lines = [
        "-- Generated by Tools/taxi_routes.py from WoW Forever %s's client tables" % build,
        "-- (TaxiPath, TaxiPathNode; wago.tools wow_classic_beta). Do not edit: regenerate.",
        "-- The flown length of each flight path in yards, keyed \"fromNodeID>toNodeID\",",
        "-- into lib.YARDS (filled in place: a host may hold it).",
        "",
        "-- LibTaxiTime.lua claims the version; this file installs only for that same",
        "-- MINOR, once (EMBEDDED-LIBRARIES section 5, rule 7).",
        "local MAJOR, MINOR = \"LibTaxiTime-1.0\", %d" % minor,
        "local lib, active = LibStub:GetLibrary(MAJOR, true)",
        "if not lib or active ~= MINOR or lib.fileMinors.Routes == MINOR then return end",
        "",
        "lib.ROUTES_BUILD = \"%s\"" % build,
        "local Y = lib.YARDS",
        "for k in pairs(Y) do Y[k] = nil end",
    ]
    def order(k):
        a, b = k.split(">")
        return int(a), int(b)
    for key in sorted(routes, key=order):
        yards, src, dst = routes[key]
        comment = ("%s > %s" % (src, dst)).replace("\n", " ")
        lines.append("Y[\"%s\"] = %d   -- %s" % (key, yards, comment))
    lines.append("")
    lines.append("lib.fileMinors.Routes = MINOR")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--db", type=Path, default=DEFAULT_DB)
    ap.add_argument("--build")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    build = args.build or newest_build(args.db)
    text = render(build, lengths(args.db, build), lib_minor())
    old = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if args.check:
        if old != text:
            print("Plugins/Flight/Routes.lua is stale for " + build)
            sys.exit(1)
        print("Routes.lua is up to date (" + build + ")")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print("wrote %s: %d routes from %s" % (OUT.relative_to(ROOT), text.count("Y[\""), build))


if __name__ == "__main__":
    main()
